print(f"[INIT] Log:   {LOG_FILE}")


def log_call(entry: dict) -> None:
    try:
        os.makedirs(os.path.dirname(LOG_FILE), exist_ok=True)
        with open(LOG_FILE, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    except Exception as e:
        print(f"[WARN] Failed to write log: {e}")


MATCH_SYSTEM_PROMPT = """\
You are a precise judge evaluating whether two bug descriptions refer to the \
SAME underlying visual glitch in a video game.

You will receive:
- A bug description generated by a vision model.
- GROUND_TRUTH_1 and GROUND_TRUTH_2

Rules:
1. MATCH if the VLM output describes the SAME bug, regardless wording.
2. NO_MATCH if the predicted description describes a DIFFERENT bug
3. Focus on WHAT went wrong not on exact vocabulary.
4. Partial overlap (same object, different bug) is NO_MATCH.

Respond with ONLY this JSON (no extra text):
{"match": true or false}"""


def build_match_prompt(
    pred: str,
    gt1: Optional[str],
    gt2: Optional[str],
) -> str:
    gt1 = (gt1 or "").strip()
    gt2 = (gt2 or "").strip()

    parts = [f"PREDICTED: {pred}"]
    if not gt1 and not gt2:
        parts.append("No glitch in this video")
    else:
        if gt1:
            parts.append(f"GROUND_TRUTH_1: {gt1}")
        if gt2:
            parts.append(f"GROUND_TRUTH_2: {gt2}")
    return "\n".join(parts)


def call_claude_match(
    pred: str,
    gt1: Optional[str],
    gt2: Optional[str],
    max_retries: int = 3,
) -> dict:
    user_prompt = build_match_prompt(pred, gt1, gt2)

    for attempt in range(max_retries):
        try:
            if MATCHER_BACKEND == "anthropic":
                response = client.messages.create(
                    model=CLAUDE_MODEL,
                    max_tokens=64,
                    temperature=0.0,
                    system=MATCH_SYSTEM_PROMPT,
                    messages=[{"role": "user", "content": user_prompt}],
                )
                raw_text = "".join(
                    block.text for block in response.content
                    if getattr(block, "type", None) == "text"
                ).strip()
            else:
                response = client.chat.completions.create(
                    model=CLAUDE_MODEL,
                    max_tokens=64,
                    temperature=0.0,
                    messages=[
                        {"role": "system", "content": MATCH_SYSTEM_PROMPT},
                        {"role": "user", "content": user_prompt},
                    ],
                )
                raw_text = (response.choices[0].message.content or "").strip()
            text = raw_text

            if text.startswith("```"):
                text = text.split("\n", 1)[-1].rsplit("```", 1)[0].strip()

            try:
                start = text.index("{")
                end = text.rindex("}") + 1
                obj = json.loads(text[start:end])
            except (ValueError, json.JSONDecodeError):
                print(
                    f"[WARN] Could not parse Claude response "
                    f"(attempt {attempt + 1}): {text[:200]}"
                )
                if attempt < max_retries - 1:
                    time.sleep(1)
                    continue
                return {
                    "match": False,
                    "reasoning": f"parse_error: {text[:100]}",
                    "raw_response": raw_text,
                    "system_prompt": MATCH_SYSTEM_PROMPT,
                    "user_prompt": user_prompt,
                }

            return {
                "match": bool(obj.get("match", False)),
                "reasoning": str(obj.get("reasoning", "")),
                "raw_response": raw_text,
                "system_prompt": MATCH_SYSTEM_PROMPT,
                "user_prompt": user_prompt,
            }

        except Exception as e:
            print(f"[ERROR] Claude call failed (attempt {attempt + 1}): {e}")
            if attempt < max_retries - 1:
                time.sleep(2 ** attempt)
                continue
            return {
                "match": False,
                "reasoning": f"api_error: {str(e)[:100]}",
                "raw_response": "",
                "system_prompt": MATCH_SYSTEM_PROMPT,
                "user_prompt": user_prompt,
            }

    return {
        "match": False,
        "reasoning": "max_retries_exceeded",
        "raw_response": "",
        "system_prompt": MATCH_SYSTEM_PROMPT,
        "user_prompt": user_prompt,
    }


class SemanticMatchRequest(BaseModel):
    predicted_description: str
    ground_truth_1: Optional[str] = None
    ground_truth_2: Optional[str] = None


class SemanticMatchResponse(BaseModel):
    match: bool
    confidence: Optional[str] = None
    reasoning: Optional[str] = None
    backend: Optional[str] = None


app = FastAPI(title="Semantic Matcher (Claude Sonnet 4)")


@app.post("/match", response_model=SemanticMatchResponse)
def semantic_match(req: SemanticMatchRequest) -> SemanticMatchResponse:
    if not req.predicted_description:
        return SemanticMatchResponse(
            match=False, reasoning="empty prediction", backend="claude"
        )
    if not req.ground_truth_1 and not req.ground_truth_2:
        return SemanticMatchResponse(
            match=False, reasoning="no ground truth", backend="claude"
        )

    result = call_claude_match(
        req.predicted_description,
        req.ground_truth_1,
        req.ground_truth_2,
    )

    log_call({
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "model": CLAUDE_MODEL,
        "system_prompt": result["system_prompt"],
        "user_prompt": result["user_prompt"],
        "predicted_description": req.predicted_description,
        "ground_truth_1": req.ground_truth_1,
        "ground_truth_2": req.ground_truth_2,
        "raw_response": result["raw_response"],
        "match": result["match"],
        "reasoning": result["reasoning"],
    })

    print(
        f"[CLAUDE] {'MATCH' if result['match'] else 'NO MATCH'} | "
        f"pred='{req.predicted_description[:60]}' | "
        f"reason='{result['reasoning'][:80]}'"
    )

    return SemanticMatchResponse(
        match=result["match"],
        confidence=None,
        reasoning=result["reasoning"],
        backend="claude",
    )


