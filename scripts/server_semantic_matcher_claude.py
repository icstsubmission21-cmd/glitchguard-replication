LOG_DIR = os.getenv("MATCHER_LOG_DIR", os.path.join(os.getcwd(), "logs"))
LOG_FILE = os.path.join(LOG_DIR, "claude_matcher_log.jsonl")

if MATCHER_BACKEND == "anthropic":
    import anthropic
